// The token radar's model: one sealed snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol that records no token and is not a wrapped, staked or bridged
// product of a token that already trades, using the same exclusion the house used to draw its
// watchlist -- but only the ten fields the snapshot carries, since `parentProtocol` is not one
// of them. The watchlist (40 protocols) is the floor, never the ceiling: the board also ranks
// every other protocol that passes the same rule below the $50M floor, so the radar finds the
// early ones instead of re-printing the floor.
//
// Implied value follows only from the snapshot's own figures, never from a hardcoded list of
// names. It is a comparables model: what would this protocol's token be worth if the market
// priced it like the tokens that already trade in its own category?
//
//   comp       = median(mcap_usd / tvl_usd) over live-token protocols in the same category
//                (at least 3 comparables, else the global median over all live protocols),
//                clamped to [0.05, 1.00]
//   base       = tvl_usd x comp
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   maturity   = 0.7 + min(age_days, 1095) / 1095 x 0.3   (age unknown: 365 days)
//   breadth    = 1 + 0.03 x min(chains - 1, 5)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// A protocol whose token already trades is never ranked: the live view shows the market's own
// market cap for it instead, so the two are never mixed.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

